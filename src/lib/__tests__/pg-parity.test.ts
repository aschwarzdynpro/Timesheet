import { describe, expect, it } from 'vitest'
import { fromIsoDate, isoWeek, mondayOf, toIsoDate } from '@/lib/week'

/**
 * Gegenprobe gegen PostgreSQL.
 *
 * Die Datenbank ordnet Zeiteintraege ueber date_trunc('week', …) und
 * EXTRACT(ISOYEAR/WEEK …) einer Reporting-Periode zu. Weicht die Oberflaeche
 * davon ab, zeigt sie eine andere Woche an als die, in der gemeldet wird –
 * und das faellt erst beim Kunden auf.
 *
 * Die Erwartungswerte stammen aus einer Abfrage gegen PostgreSQL 17 und decken
 * die Jahreswechsel 2024/25 bis 2027/28 sowie einen Monatswechsel ab.
 * Format: datum=isojahr/kalenderwoche/wochenstart
 */
const AUS_POSTGRES = `
  2024-12-25=2024/52/2024-12-23 2024-12-26=2024/52/2024-12-23 2024-12-27=2024/52/2024-12-23 2024-12-28=2024/52/2024-12-23
  2024-12-29=2024/52/2024-12-23 2024-12-30=2025/1/2024-12-30 2024-12-31=2025/1/2024-12-30 2025-01-01=2025/1/2024-12-30
  2025-01-02=2025/1/2024-12-30 2025-01-03=2025/1/2024-12-30 2025-01-04=2025/1/2024-12-30 2025-01-05=2025/1/2024-12-30
  2025-01-06=2025/2/2025-01-06 2025-01-07=2025/2/2025-01-06 2025-01-08=2025/2/2025-01-06 2025-12-25=2025/52/2025-12-22
  2025-12-26=2025/52/2025-12-22 2025-12-27=2025/52/2025-12-22 2025-12-28=2025/52/2025-12-22 2025-12-29=2026/1/2025-12-29
  2025-12-30=2026/1/2025-12-29 2025-12-31=2026/1/2025-12-29 2026-01-01=2026/1/2025-12-29 2026-01-02=2026/1/2025-12-29
  2026-01-03=2026/1/2025-12-29 2026-01-04=2026/1/2025-12-29 2026-01-05=2026/2/2026-01-05 2026-01-06=2026/2/2026-01-05
  2026-01-07=2026/2/2026-01-05 2026-01-08=2026/2/2026-01-05 2026-02-24=2026/9/2026-02-23 2026-02-25=2026/9/2026-02-23
  2026-02-26=2026/9/2026-02-23 2026-02-27=2026/9/2026-02-23 2026-02-28=2026/9/2026-02-23 2026-03-01=2026/9/2026-02-23
  2026-03-02=2026/10/2026-03-02 2026-03-03=2026/10/2026-03-02 2026-03-04=2026/10/2026-03-02 2026-03-05=2026/10/2026-03-02
  2026-03-06=2026/10/2026-03-02 2026-03-07=2026/10/2026-03-02 2026-03-08=2026/10/2026-03-02 2026-03-09=2026/11/2026-03-09
  2026-03-10=2026/11/2026-03-09 2026-12-25=2026/52/2026-12-21 2026-12-26=2026/52/2026-12-21 2026-12-27=2026/52/2026-12-21
  2026-12-28=2026/53/2026-12-28 2026-12-29=2026/53/2026-12-28 2026-12-30=2026/53/2026-12-28 2026-12-31=2026/53/2026-12-28
  2027-01-01=2026/53/2026-12-28 2027-01-02=2026/53/2026-12-28 2027-01-03=2026/53/2026-12-28 2027-01-04=2027/1/2027-01-04
  2027-01-05=2027/1/2027-01-04 2027-01-06=2027/1/2027-01-04 2027-01-07=2027/1/2027-01-04 2027-01-08=2027/1/2027-01-04
  2027-12-25=2027/51/2027-12-20 2027-12-26=2027/51/2027-12-20 2027-12-27=2027/52/2027-12-27 2027-12-28=2027/52/2027-12-27
  2027-12-29=2027/52/2027-12-27 2027-12-30=2027/52/2027-12-27 2027-12-31=2027/52/2027-12-27 2028-01-01=2027/52/2027-12-27
  2028-01-02=2027/52/2027-12-27 2028-01-03=2028/1/2028-01-03 2028-01-04=2028/1/2028-01-03 2028-01-05=2028/1/2028-01-03
  2028-01-06=2028/1/2028-01-03 2028-01-07=2028/1/2028-01-03 2028-01-08=2028/1/2028-01-03
`.trim().split(/\s+/)

describe('Wochenlogik stimmt mit PostgreSQL ueberein', () => {
  it(`liefert fuer alle ${AUS_POSTGRES.length} Stichtage dieselbe Woche`, () => {
    const abweichungen: string[] = []

    for (const eintrag of AUS_POSTGRES) {
      const [iso, erwartet] = eintrag.split('=')
      const [pgJahr, pgWoche, pgMontag] = erwartet!.split('/')
      const datum = fromIsoDate(iso!)
      const ts = isoWeek(datum)
      const tsMontag = toIsoDate(mondayOf(datum))

      if (String(ts.year) !== pgJahr || String(ts.week) !== pgWoche || tsMontag !== pgMontag) {
        abweichungen.push(`${iso}: PG ${erwartet} <-> TS ${ts.year}/${ts.week}/${tsMontag}`)
      }
    }

    expect(abweichungen).toEqual([])
  })
})
